// Теория: нота = {l: буква 0..6 (C..B), a: альтерация -2..2}. Всё написание выводится из букв + полутонов.
const LET = 'CDEFGAB', SYL = ['До', 'Ре', 'Ми', 'Фа', 'Соль', 'Ля', 'Си'], NAT = [0, 2, 4, 5, 7, 9, 11];
const ACC = { '-2': '𝄫', '-1': '♭', 0: '', 1: '♯', 2: '𝄪' };
const MAJ = [0, 2, 4, 5, 7, 9, 11], MIN = [0, 2, 3, 5, 7, 8, 10];
const mod = (n, m) => (n % m + m) % m;
const rng = (a, b) => Array.from({ length: Math.max(0, b - a + 1) }, (_, i) => a + i);
const N = (l, a = 0) => ({ l, a });
const pc = n => mod(NAT[n.l] + n.a, 12);
const same = (x, y) => x.l === y.l && x.a === y.a;
const nk = n => n.l + ':' + n.a;
// нота на `steps` букв и `semis` полутонов выше
const up = (n, steps, semis) => { const l = mod(n.l + steps, 7); return N(l, mod(pc(n) + semis - NAT[l] + 6, 12) - 6); };
// k квинт от До (k<0 — кварты): тоника мажора с k знаками (+диезы, −бемоли)
const fifth = k => { const l = mod(4 * k, 7); return N(l, mod(7 * k - NAT[l] + 6, 12) - 6); };
const sharpOf = p => NAT.includes(p) ? N(NAT.indexOf(p)) : N(NAT.indexOf(p - 1), 1);
const flatOf = p => NAT.includes(p) ? N(NAT.indexOf(p)) : N(NAT.indexOf(p + 1), -1);

// h: немецкая система — Си = H, Си♭ = B
function nm(n, naming, h) {
  if (naming === 'syl') return SYL[n.l] + ACC[n.a];
  if (h && n.l === 6) return n.a === -1 ? 'B' : 'H' + ACC[n.a];
  return LET[n.l] + ACC[n.a];
}

const NAT7 = rng(0, 6).map(l => N(l));
const NOTES17 = [...NAT7, ...[0, 1, 3, 4, 5].map(l => N(l, 1)), ...[1, 2, 4, 5, 6].map(l => N(l, -1))];
const ENH = [[N(0, 1), N(1, -1)], [N(1, 1), N(2, -1)], [N(3, 1), N(4, -1)], [N(4, 1), N(5, -1)], [N(5, 1), N(6, -1)],
  [N(2, 1), N(3)], [N(6, 1), N(0)], [N(3, -1), N(2)], [N(0, -1), N(6)]];

// тональность K = {k: знаков (+♯/−♭), m: 0 мажор / 1 минор}
const keys = (sigs, minor) => rng(-sigs, sigs).flatMap(k => minor ? [{ k, m: 0 }, { k, m: 1 }] : [{ k, m: 0 }]);
const tonic = K => fifth(K.k + 3 * K.m);
const scale = K => rng(0, 6).map(d => up(tonic(K), d, (K.m ? MIN : MAJ)[d]));
const sigNotes = k => k > 0 ? rng(0, k - 1).map(i => N(fifth(i - 1).l, 1)) : rng(0, -k - 1).map(i => N(fifth(5 - i).l, -1));

